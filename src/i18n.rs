use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
pub enum Language {
    #[default]
    De,
    En,
}

impl Language {
    pub fn label(self) -> &'static str {
        match self {
            Language::De => "Deutsch",
            Language::En => "English",
        }
    }
}

